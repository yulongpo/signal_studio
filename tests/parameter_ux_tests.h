inline void UxTests::uxS06_invalidDraftRecovery() {
  QWidget root;
  root.resize(600, 400);
  QPushButton anchor("Settings", &root), outside("Outside", &root);
  anchor.setGeometry(20, 20, 100, 30);
  outside.setGeometry(450, 350, 100, 30);
  auto* content = new QWidget;
  auto* layout = new QVBoxLayout(content);
  auto* spin = new ParameterIntSpinBox(content);
  spin->setRange(10, 20); spin->setValue(12);
  auto* adaptive = new AdaptiveValueEdit(UnitKind::Scalar, 3, content);
  layout->addWidget(spin); layout->addWidget(adaptive);
  ParameterInputPolicy policy(&root);
  SettingsPopoverHost host(&root);
  auto* frame = host.add(&anchor, content, "invalidSettings");
  root.show();
  QVERIFY(QTest::qWaitForWindowExposed(&root));
  QTest::mouseClick(&anchor, Qt::LeftButton);
  auto* editor = spin->findChild<QLineEdit*>();
  QTest::mouseClick(editor, Qt::LeftButton);
  editor->selectAll(); QTest::keyClicks(editor, "2");
  QSignalSpy values(spin, &QSpinBox::valueChanged);
  QTest::keyClick(editor, Qt::Key_Return);
  QCOMPARE(spin->value(), 12);
  QCOMPARE(editor->text(), QString("2"));
  QVERIFY(spin->property("invalid").toBool());
  QVERIFY(spin->property("parameterDraft").toBool());
  QTest::keyClick(editor, Qt::Key_Tab);
  QCOMPARE(spin->value(), 12);
  QCOMPARE(editor->text(), QString("2"));
  QCOMPARE(values.count(), 0);
  QTest::keyClick(adaptive, Qt::Key_Backtab);
  QTest::keyClick(editor, Qt::Key_Escape);
  QVERIFY(!frame->isVisible());
  QCOMPARE(editor->text(), QString("12"));
  QVERIFY(!spin->property("invalid").toBool());
  QTest::mouseClick(&anchor, Qt::LeftButton);
  QTest::mouseClick(adaptive, Qt::LeftButton);
  adaptive->selectAll(); QTest::keyClicks(adaptive, "bad-value");
  QSignalSpy applied(adaptive, &AdaptiveValueEdit::valueCommitted);
  QTest::keyClick(adaptive, Qt::Key_Return);
  QCOMPARE(adaptive->value(), 3.0);
  QCOMPARE(adaptive->text(), QString("bad-value"));
  QVERIFY(adaptive->property("parameterDraft").toBool());
  QVERIFY(adaptive->property("invalid").toBool());
  QEvent deactivate(QEvent::ApplicationDeactivate);
  QCoreApplication::sendEvent(qApp, &deactivate);
  QVERIFY(!frame->isVisible());
  QTest::mouseClick(&anchor, Qt::LeftButton);
  QCOMPARE(adaptive->text(), QString("bad-value"));
  QCOMPARE(adaptive->value(), 3.0);
  QTest::mouseClick(&outside, Qt::LeftButton);
  QTRY_VERIFY(!frame->isVisible());
  QCOMPARE(adaptive->text(), QString("bad-value"));
  QCOMPARE(applied.count(), 0);
  QTest::mouseClick(&anchor, Qt::LeftButton);
  QTest::keyClick(adaptive, Qt::Key_Escape);
  QCOMPARE(adaptive->text(), QString("3"));
  QVERIFY(!adaptive->property("parameterDraft").toBool());
  QVERIFY(!adaptive->property("invalid").toBool());
}

inline void UxTests::uxS03_framePsdPreservesSettings() {
  MainWindow window;
  window.session().addDemoFile();
  expose(window);
  QTest::mouseClick(window.findChild<QAbstractButton*>("psdMode"), Qt::LeftButton);
  auto* file = window.session().activeFile();
  const auto id = file->metadata.id;
  file->display.psdSize = 8192;
  file->display.stftSize = 1024;
  window.session().pinCursor(id, file->view.time.begin + 100, file->metadata.centerFrequencyHz, false);
  window.refresh();
  auto* source = window.findChild<QComboBox*>("psdSource");
  QVERIFY(source && source->isVisible());
  source->setFocus(); QTest::keyClick(source, Qt::Key_Down);
  QVERIFY(window.session().linkedCursor(id).framePsd);
  auto* n = window.findChild<QComboBox*>("psdFft");
  QCOMPARE(n->currentText(), QString("1024"));
  QVERIFY(!n->isEnabled());
  auto* palette = window.findChild<QComboBox*>("colormap");
  QVERIFY(palette->isVisible());
  const auto previousPalette = file->display.palette;
  palette->setFocus();
  QTest::keyClick(palette, palette->currentIndex() > 0 ? Qt::Key_Home : Qt::Key_Down);
  QVERIFY(file->display.palette != previousPalette);
  QCOMPARE(file->display.psdSize, 8192);
  QCOMPARE(file->display.stftSize, 1024);
  source->setFocus(); QTest::keyClick(source, Qt::Key_Up);
  QVERIFY(!window.session().linkedCursor(id).framePsd);
  QCOMPARE(n->currentText(), QString("8192"));
  QVERIFY(n->isEnabled());
}
